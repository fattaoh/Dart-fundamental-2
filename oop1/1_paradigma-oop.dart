/**
 * paradigma adalah pola pikir, kerangka, cara pandang
 * paradigma oop = didasari pada adanya konsep objek
 * 
 * 4 pilar oop:
 * -encapsulation(pembungkusan)
 * -abstraction (penyederhanaan)
 * -polimorfisme (banyak bentuk)
 * -pewarisan (inheritance) (penurunan)
 * 
 * Encapsulation = membungkus data dan method menjadi satu kesatuan
 * berfungsi: mengumpulkan data yang didapat yang tidak dapat diakses langsung
 * contoh: pada kasus ucup kita tidak bisa mengubah berat badannya tapi kita bisa
 *  menambahkannya dengan fungsi / method()makan
 * 
 * Abstraction = penerapan alami dari encapsulation
 * sebuah objek yang hanya menunjukan operasinya secara high level
 * contoh = kita hanya perlu tahu bagaimana ucup makan tapi kita tidak perlu tau
 * tentang sistem metabolisme di tubuhnya ucup
 * 
 * Inheritance = pewarisan
 * objek bisa memiliki karakter fisik dan sifat yg sama
 * namun mereka bukan objek yg sama
 * Inheritance memiliki sifat dan perilaku yg umum seperti manusia lain.
 * berat badan, tinggi, warna, dll
 * maka ucup sebagai objek turunan(sub class)
 * induk classnya adalah super class
 * 
 * Polymorphism = banyak bentuk
 * objek dapat memiliki bentuk dan implementasi yang berbeda 
 * pada satu metode yg sama
 * manusia bisa bergerak tapi memiliki cara bergerak yang berbeda
 */